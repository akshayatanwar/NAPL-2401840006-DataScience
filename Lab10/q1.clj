(println "=== 1. LIST ===")
(def orig-list '(10 20 30 40))
(def new-list (conj orig-list 5))

(println "Original List:" orig-list)
(println "First element:" (first orig-list))
(println "Rest elements:" (rest orig-list))
(println "New List (after conj 5):" new-list)
(println "Original List remains unchanged:" orig-list)
(println)

(println "=== 2. VECTOR ===")
(def orig-vec [10 20 30 40])
(def new-vec (conj orig-vec 50))

(println "Original Vector:" orig-vec)
(println "Element at index 2:" (get orig-vec 2))
(println "Count of elements:" (count orig-vec))
(println "New Vector (after conj 50):" new-vec)
(println "Original Vector remains unchanged:" orig-vec)
(println)

(println "=== 3. MAP ===")
(def orig-map {:name "Aarav" :age 21 :city "Delhi"})
(def assoc-map (assoc orig-map :role "Developer"))
(def dissoc-map (dissoc orig-map :age))

(println "Original Map:" orig-map)
(println "Get :name ->" (get orig-map :name))
(println "New Map (after assoc :role):" assoc-map)
(println "New Map (after dissoc :age):" dissoc-map)
(println "Original Map remains unchanged:" orig-map)
(println)

(println "=== 4. SET ===")
(def orig-set #{:apple :banana :mango})
(def conj-set (conj orig-set :orange))
(def disj-set (disj orig-set :banana))

(println "Original Set:" orig-set)
(println "Contains :mango? ->" (contains? orig-set :mango))
(println "New Set (after conj :orange):" conj-set)
(println "New Set (after disj :banana):" disj-set)
(println "Original Set remains unchanged:" orig-set)